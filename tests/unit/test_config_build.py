def _active_and_aside(text: str) -> tuple[set[str], set[str]]:
    lines = text.split("\n")
    return (
        {line for line in lines if line and not line.startswith("#")},
        {line[len(NOT_CARRIED) :] for line in lines if line.startswith(NOT_CARRIED)},
    )


@given(
    st.lists(st.sampled_from(_POOL + _REGENERATED), max_size=14),
    st.booleans(),
    st.booleans(),
)
def test_a_line_the_build_does_not_write_always_comes_back(
    lines: list[str], with_gone: bool, with_objective_labels: bool
) -> None:
    """Carried or set aside, never dropped; and the next build changes nothing."""
    devices = _stand()
    if with_gone:
        devices.append(_device("Gone", "Stage"))
    if not with_objective_labels:
        devices = [d for d in devices if d.label != "Objective"]
    scan = _scan(devices)
    previous = "\n".join(lines) + "\n"

    first = render_config(_plan(scan, previous), header=HEADER)

    active, aside = _active_and_aside(first)
    for line in lines:
        if line in _REGENERATED:
            continue
        assert line in active or line in aside, f"{line!r} was lost"
    # A line is carried or set aside, never both.
    assert not (active & aside)
    # The file the build wrote is read back as the file it replaces, and the build
    # of that one says the same again: nothing drifts from one build to the next.
    # (The first rebuild differs by a comment: the labels the first build wrote
    # are now the file's, and the heading says so.)
    second = render_config(_plan(scan, first), header=HEADER)
    assert _active_and_aside(second) == (active, aside)
    third = render_config(_plan(scan, second), header=HEADER)
    assert third == second
    # A block set aside for a device that was missing is carried once it is back.
    preset_a = "ConfigGroup,Channel,A,Gone,State,1"
    if preset_a in lines and not with_gone:
        back = _scan([*devices, _device("Gone", "Stage")])
        active_back, _ = _active_and_aside(
            render_config(_plan(back, second), header=HEADER)
        )
        assert preset_a in active_back
