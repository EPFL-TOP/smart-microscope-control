"""The plan and the text of ``smc config build`` (design m2 §10.4 and §10.5).

Pure: a ``BuildScan`` built by hand goes in, a plan and a ``.cfg`` text come out.
The rule under test is that a rebuild never loses what it does not generate
(FM-107): each preset, pixel size, device's labels and delay is carried or set
aside whole, and what is set aside comes back once it applies again.
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

import pytest
from hypothesis import given
from hypothesis import strategies as st

from smc.discovery.config_build import (
    FIELD_COUNTS,
    NOT_CARRIED,
    ConfigPlan,
    parse_previous,
    plan_config,
    read_previous,
    render_config,
)
from smc.discovery.models import BuildScan, BuiltDevice, ProbedDevice, ProbeResult
from smc.hardware.roles import Role

HEADER = ["Generated by smc config build", "Profile test"]


# --- values built by hand ------------------------------------------------------------


def _device(
    label: str,
    type_name: str = "Generic",
    *,
    library: str = "Fake",
    parent: str | None = "H",
    labels: Sequence[str] = (),
) -> BuiltDevice:
    return BuiltDevice(
        label=label,
        library=library,
        name=label,
        type=type_name,
        parent=parent,
        state_labels=list(labels),
    )


def _hub(label: str = "H", library: str = "Fake") -> BuiltDevice:
    return _device(label, "Hub", library=library, parent=None)


def _rows(devices: Sequence[BuiltDevice]) -> list[ProbedDevice]:
    return [ProbedDevice(name=d.label, type=d.type, status="ok") for d in devices]


def _stand() -> list[BuiltDevice]:
    """A hub and what a Nikon-like stand gives: a camera, drives, a shutter, wheels."""
    return [
        _hub(),
        _device("Cam", "Camera"),
        _device("Z", "Stage"),
        _device("XY", "XYStage"),
        _device("Shut", "Shutter"),
        _device("Wheel", "State", labels=["Open", "Closed"]),
        _device("Objective", "State", labels=["10x", "20x"]),
    ]


def _scan(
    devices: Sequence[BuiltDevice] | None = None,
    *extra_rows: ProbedDevice,
    error: str | None = None,
    camera: ProbeResult | None = None,
    camera_devices: Sequence[BuiltDevice] = (),
    complete: bool = True,
) -> BuildScan:
    built = list(_stand() if devices is None else devices)
    return BuildScan(
        stand=ProbeResult(
            adapter="Fake", devices=[*_rows(built), *extra_rows], error=error
        ),
        camera=camera,
        devices=[*built, *camera_devices],
        complete=complete,
    )


def _cfg(*lines: str) -> str:
    return "\n".join(lines) + "\n"


def _plan(scan: BuildScan, previous: str | None = None, **kwargs: object) -> ConfigPlan:
    return plan_config(
        scan,
        previous=parse_previous(previous) if previous is not None else None,
        **kwargs,  # type: ignore[arg-type]
    )


def _text(plan: ConfigPlan) -> list[str]:
    return render_config(plan, header=HEADER).splitlines()


def _keys(blocks: Sequence[object]) -> list[str]:
    return [b.key for b in blocks]  # type: ignore[attr-defined]


# --- carried over, or set aside whole --------------------------------------------------

PRESETS = (
    "ConfigGroup,Channel,DAPI,Wheel,Label,Open",
    "ConfigGroup,Channel,DAPI,Cam,Exposure,10",
    "ConfigGroup,Channel,DAPI,Core,Shutter,Shut",
    "ConfigPixelSize,Res10x,Objective,Label,10x",
    "PixelSize_um,Res10x,0.65",
    "Delay,Shut,5",
    "FocusDirection,Z,0",
)


def test_presets_and_pixel_sizes_of_the_previous_file_are_carried_verbatim() -> None:
    plan = _plan(_scan(), _cfg(*PRESETS))

    assert plan.not_carried == []
    assert _keys(plan.carried) == [
        "Channel/DAPI",
        "Res10x",
        "Delay Shut",
        "FocusDirection Z",
    ]
    text = _text(plan)
    start = text.index("# Carried over from the previous configuration")
    # Line by line, in the previous file's order, as it was written.
    assert [line for line in text[start + 1 :] if line] == list(PRESETS)


def test_the_lines_of_one_preset_come_back_together_even_when_apart_in_the_file() -> (
    None
):
    previous = _cfg(
        "ConfigGroup,Channel,A,Wheel,State,0",
        "ConfigGroup,Channel,B,Wheel,State,1",
        "ConfigGroup,Channel,A,Cam,Exposure,10",
    )

    parsed = parse_previous(previous)

    assert [(b.key, b.lines) for b in parsed.blocks] == [
        (
            "Channel/A",
            (
                "ConfigGroup,Channel,A,Wheel,State,0",
                "ConfigGroup,Channel,A,Cam,Exposure,10",
            ),
        ),
        ("Channel/B", ("ConfigGroup,Channel,B,Wheel,State,1",)),
    ]
    assert parsed.blocks[0].devices == ("Wheel", "Cam")


def test_a_preset_that_names_an_absent_device_is_set_aside_whole() -> None:
    previous = _cfg(
        "ConfigGroup,Channel,DAPI,Wheel,State,0",
        "ConfigGroup,Channel,DAPI,Gone,State,1",
        "ConfigGroup,Channel,DAPI,Cam,Exposure,10",
    )

    plan = _plan(_scan(), previous)

    assert plan.carried == []
    ((block, why),) = plan.not_carried
    assert block.key == "Channel/DAPI"
    assert why == "names Gone, which this configuration does not load"
    text = _text(plan)
    # All three lines are comments: a preset in part would load, and apply the
    # two lines that do not name the absent device.
    assert [line for line in text if line.startswith("ConfigGroup")] == []
    assert [line for line in text if line.startswith(NOT_CARRIED)] == [
        NOT_CARRIED + line for line in block.lines
    ]
    assert len(block.lines) == 3
    assert "# Channel/DAPI: names Gone, which this configuration does not load" in text


def test_a_set_aside_block_is_carried_again_once_its_device_is_back() -> None:
    previous = _cfg(
        "ConfigGroup,Channel,DAPI,Wheel,State,0",
        "ConfigGroup,Channel,DAPI,Gone,State,1",
    )
    first = render_config(_plan(_scan(), previous), header=HEADER)
    # The first build could not carry it: not one of its lines is active.
    assert not [line for line in first.splitlines() if line.startswith("ConfigGroup")]

    # The next build reads the file the first one wrote: the device is back.
    with_gone = _scan([*_stand(), _device("Gone", "Stage")])
    second = _plan(with_gone, first)

    assert second.not_carried == []
    # (The wheels' own labels, written by the first build, come back as labels of
    # the file: they are in the block list too.)
    assert "Channel/DAPI" in _keys(second.carried)
    assert [line for line in _text(second) if line.startswith("ConfigGroup")] == [
        "ConfigGroup,Channel,DAPI,Wheel,State,0",
        "ConfigGroup,Channel,DAPI,Gone,State,1",
    ]


def test_a_preset_that_selects_a_label_the_device_lacks_is_set_aside() -> None:
    previous = _cfg(
        "ConfigGroup,Channel,OK,Wheel,Label,Open",
        "ConfigGroup,Channel,Bad,Wheel,Label,Missing",
        "ConfigPixelSize,Res40x,Objective,Label,40x",
        "PixelSize_um,Res40x,0.16",
    )

    plan = _plan(_scan(), previous)

    assert _keys(plan.carried) == ["Channel/OK"]
    reasons = {block.key: why for block, why in plan.not_carried}
    assert reasons == {
        "Channel/Bad": "sets Wheel to the label Missing, which it does not have here",
        "Res40x": "sets Objective to the label 40x, which it does not have here",
    }
    # Both lines of the pixel size go: a resolution without its device setting
    # would be a pixel size for no objective at all.
    text = _text(plan)
    assert NOT_CARRIED + "PixelSize_um,Res40x,0.16" in text
    assert "PixelSize_um,Res40x,0.16" not in text


def test_a_core_setting_that_names_an_absent_device_sets_the_preset_aside() -> None:
    previous = _cfg(
        "ConfigGroup,Channel,BF,Wheel,State,0",
        "ConfigGroup,Channel,BF,Core,Shutter,Gone",
        "ConfigGroup,Channel,Ok,Core,Shutter,Shut",
        "ConfigGroup,System,Startup,Core,ChannelGroup,Channel",
    )

    plan = _plan(_scan(), previous)

    assert _keys(plan.carried) == ["Channel/Ok", "System/Startup"]
    ((block, why),) = plan.not_carried
    assert block.key == "Channel/BF"
    assert block.devices == ("Wheel", "Gone")
    assert why == "names Gone, which this configuration does not load"


def test_previous_labels_replace_the_devices_own_for_that_device_only() -> None:
    previous = _cfg(
        "Label,Objective,0,4x",
        "Label,Objective,1,40x",
        # Selects what the device called itself; the labels of the file win.
        "ConfigGroup,Channel,Own,Objective,Label,10x",
        "ConfigGroup,Channel,New,Objective,Label,40x",
    )

    plan = _plan(_scan(), previous)

    text = _text(plan)
    assert "Label,Objective,0,4x" in text
    assert "Label,Objective,1,40x" in text
    assert "Label,Objective,0,10x" not in text
    assert "# Objective (from the previous configuration)" in text
    # The wheel had none in the file: it keeps its own.
    assert "# Wheel" in text
    assert "Label,Wheel,0,Open" in text
    assert "Label,Wheel,1,Closed" in text
    assert _keys(plan.carried) == ["Objective", "Channel/New"]
    assert [block.key for block, _ in plan.not_carried] == ["Channel/Own"]
    # Labels are before the presets: a preset that selects one finds it defined.
    assert text.index("Label,Objective,1,40x") < text.index(
        "ConfigGroup,Channel,New,Objective,Label,40x"
    )


def test_previous_labels_of_a_device_that_is_not_a_state_device_here_are_set_aside() -> (
    None
):
    previous = _cfg("Label,Cam,0,a", "Label,Gone,0,b", "Label,Wheel,0,Zero")

    plan = _plan(_scan(), previous)

    reasons = {block.key: why for block, why in plan.not_carried}
    # MMCore fails the whole load on a Label line of a device it does not load.
    assert reasons["Gone"] == "names Gone, which this configuration does not load"
    assert "Camera device" in reasons["Cam"]
    assert _keys(plan.carried) == ["Wheel"]
    assert NOT_CARRIED + "Label,Gone,0,b" in _text(plan)
    assert "Label,Gone,0,b" not in _text(plan)


def test_a_label_or_delay_line_for_an_absent_device_is_set_aside() -> None:
    # Each would fail MMCore's whole load ("No device with label"), §10.1.
    previous = _cfg("Label,Gone,0,a", "Delay,Gone,5", "FocusDirection,Gone,1")

    plan = _plan(_scan(), previous)

    assert plan.carried == []
    assert [block.key for block, _ in plan.not_carried] == [
        "Gone",
        "Delay Gone",
        "FocusDirection Gone",
    ]
    active = [line for line in _text(plan) if not line.startswith("#") and line]
    # (The wheels' own `Label` lines are the build's; none of them is Gone's.)
    assert not [line for line in active if ",Gone," in line]
    assert NOT_CARRIED + "Delay,Gone,5" in _text(plan)


def test_a_line_with_the_wrong_field_count_is_set_aside_not_carried() -> None:
    previous = _cfg(
        "ImageSynchro,Shut",
        "Label,Wheel,0,a,b",  # a label with a comma: MMCore refuses the whole file
        "ConfigGroup,Channel,Empty,Wheel",
        "ConfigGroup,Channel,Ok,Wheel,State,0",
    )

    plan = _plan(_scan(), previous)

    assert _keys(plan.carried) == ["Channel/Ok"]
    reasons = dict((block.lines[0], why) for block, why in plan.not_carried)
    assert reasons["ImageSynchro,Shut"] == "not a line this Micro-Manager reads"
    assert reasons["Label,Wheel,0,a,b"] == "not a line this Micro-Manager reads"
    assert reasons["ConfigGroup,Channel,Empty,Wheel"] == (
        "not a line this Micro-Manager reads"
    )
    text = _text(plan)
    for line in (
        "ImageSynchro,Shut",
        "Label,Wheel,0,a,b",
        "ConfigGroup,Channel,Empty,Wheel",
    ):
        assert NOT_CARRIED + line in text
        assert line not in text


