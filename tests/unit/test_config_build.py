def test_a_device_name_with_a_comma_or_line_break_is_left_out() -> None:
    devices = [
        *_stand(),
        _device("a,b", "Generic"),
        _device("x\ny", "Generic"),
        _device(" padded ", "Generic"),
        _device("tab\there", "Generic"),
    ]

    plan = _plan(_scan(devices))

    written = {d.label for d in plan.devices}
    assert not written & {"a,b", "x\ny", " padded ", "tab\there"}
    assert {key for key, _ in plan.left_out} == {
        "Fake/a,b",
        "Fake/x\ny",
        "Fake/ padded ",
        "Fake/tab\there",
    }
    assert all(
        why == "its name cannot be written in a .cfg line" for _, why in plan.left_out
    )
    # The file is still one device per line: nothing of the name leaked a line.
    text = render_config(plan, header=HEADER)
    assert "x\ny" not in text
    # Only the comment that says why it was left out may name a device that
    # cannot be written: no directive line does.
    active = [line for line in text.splitlines() if line and not line.startswith("#")]
    assert not [line for line in active if "a,b" in line or "padded" in line]


def test_a_device_whose_hub_is_left_out_is_left_out_with_it() -> None:
    hub = _hub("Bad,hub")
    child = _device("Child", "Generic", parent="Bad,hub")
    grandchild = _device("Grand", "Generic", parent="Child")

    plan = _plan(_scan([_hub(), hub, child, grandchild]))

    assert [d.label for d in plan.devices] == ["H"]
