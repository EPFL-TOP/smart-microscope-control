def test_a_slot_of_the_previous_file_chooses_the_role_and_the_profile_overrides_it() -> (
    None
):
    devices = [_hub(), _device("CamA", "Camera"), _device("CamB", "Camera")]
    previous = _cfg("Property,Core,Camera,CamB")

    from_file = _plan(_scan(devices), previous)
    overridden = _plan(_scan(devices), previous, overrides={Role.camera: "CamA"})
    no_file = _plan(_scan(devices))

    assert (from_file.roles.get(Role.camera), from_file.roles.sources[Role.camera]) == (
        "CamB",
        "core",
    )
    assert (
        overridden.roles.get(Role.camera),
        overridden.roles.sources[Role.camera],
    ) == ("CamA", "profile")
    assert no_file.roles.get(Role.camera) == "CamA"
    assert "Property,Core,Camera,CamB" in _text(from_file)
    assert "Property,Core,Camera,CamA" in _text(overridden)


def test_a_slot_naming_a_device_this_build_lacks_is_warned_and_the_heuristic_used() -> (
    None
):
    plan = _plan(_scan(), _cfg("Property,Core,Camera,Camera-1"))

    assert plan.roles.get(Role.camera) == "Cam"
    assert any("Camera-1" in warning for warning in plan.roles.warnings)


def test_profile_exclusions_reach_the_roles() -> None:
    devices = [_hub(), _device("CamA", "Camera"), _device("CamB", "Camera")]

    plan = _plan(_scan(devices), exclusions={Role.camera: ["CamA"]})

    assert plan.roles.get(Role.camera) == "CamB"


def test_a_core_slot_set_to_a_device_of_another_type_is_not_written() -> None:
    # `resolve` honours a profile that assigns the shutter to a State device;
    # MMCore would refuse `Property,Core,Shutter,Wheel` and the whole load fails.
    plan = _plan(_scan(), overrides={Role.shutter: "Wheel"})

    text = _text(plan)
    assert not [line for line in text if line.startswith("Property,Core,Shutter")]
    assert "Property,Core,AutoShutter,1" not in text
    assert any("no Property,Core,Shutter line was written" in n for n in plan.notes)


