def test_bytes_that_are_not_utf8_survive_a_rebuild(tmp_path: Path) -> None:
    line = b"ConfigGroup,Channel,\xb5m,Wheel,State,1"
    previous = tmp_path / "previous.cfg"
    previous.write_bytes(line + b"\r\n")

    def rebuild(scan: BuildScan, source: Path, target: Path) -> bytes:
        plan = plan_config(scan, previous=read_previous(source))
        text = render_config(plan, header=HEADER)
        with target.open(
            "w", encoding="utf-8", errors="surrogateescape", newline="\n"
        ) as f:
            f.write(text)
        return target.read_bytes()

    carried = rebuild(_scan(), previous, tmp_path / "a.cfg")
    # Carried: the cp1252 byte is the byte it was, and the line ends are LF.
    assert line + b"\n" in carried
    assert b"\r" not in carried

    # Set aside, then carried again once the device is back: the same bytes.
    no_wheel = _scan([_hub(), _device("Cam", "Camera")])
    aside = rebuild(no_wheel, tmp_path / "a.cfg", tmp_path / "b.cfg")
    assert b"# not carried: " + line + b"\n" in aside
    assert line + b"\n" not in aside.replace(b"# not carried: " + line, b"")
    again = rebuild(_scan(), tmp_path / "b.cfg", tmp_path / "c.cfg")
    assert line + b"\n" in again


