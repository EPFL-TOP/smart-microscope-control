def _camera_walk(
    devices: Sequence[BuiltDevice], *extra: ProbedDevice, **kw: object
) -> ProbeResult:
    return ProbeResult(adapter="Seq", devices=[*_rows(devices), *extra], **kw)  # type: ignore[arg-type]


def test_a_camera_adapter_without_a_camera_refuses() -> None:
    cam_devices = [
        _hub("THub", "Seq"),
        _device("TShutter-0", "Shutter", library="Seq", parent="THub"),
    ]

    plan = _plan(_scan(camera=_camera_walk(cam_devices), camera_devices=cam_devices))

    assert plan.refusals == ["Seq: no camera initialised"]


def test_a_camera_adapter_that_cannot_be_walked_refuses_with_its_error() -> None:
    plan = _plan(
        _scan(camera=ProbeResult(adapter="Seq", error="adapter not installed"))
    )

    assert plan.refusals == ["Seq: adapter not installed"]


def test_a_camera_adapter_whose_hub_failed_refuses() -> None:
    failed = ProbedDevice(name="THub", type="Hub", status="failed", error="no")

    plan = _plan(_scan(camera=_camera_walk([], failed)))

    assert plan.refusals == ["hub THub of Seq did not initialise"]


def test_the_stand_that_failed_does_not_hide_the_camera_diagnosis() -> None:
    # Both walks always run: one visit says what is wrong with each.
    stand = ProbedDevice(name="H", type="Hub", status="failed", error="stand is off")
    plan = _plan(_scan([], stand, camera=_camera_walk([])))

    assert plan.refusals == [
        "hub H of Fake did not initialise",
        "Seq: no camera initialised",
    ]


