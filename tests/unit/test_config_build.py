def test_a_failed_hub_refuses_even_when_another_hub_initialised() -> None:
    # The Ti2-E: with the stand off, the simulator answers, and a file built
    # from it would load a stand that is not there.
    devices = [_hub("Simulator"), _device("Cam", "Camera", parent="Simulator")]
    stand = ProbedDevice(
        name="Stand",
        type="Hub",
        status="failed",
        error="(Error message unavailable) (-10)",
    )

    plan = _plan(_scan(devices, stand))

    assert plan.refusals == ["hub Stand of Fake did not initialise"]
    assert not plan.writable


def test_a_skipped_hub_is_not_a_refusal() -> None:
    # `--skip Ti2-E__0` is how a build of the simulator is asked for.
    devices = [_hub("Simulator"), _device("Cam", "Camera", parent="Simulator")]
    stand = ProbedDevice(
        name="Stand", type="Hub", status="not-probed", reason="left out: --skip Stand"
    )

    plan = _plan(_scan(devices, stand))

    assert plan.refusals == []
    assert plan.writable
    assert plan.left_out == [("Fake/Stand", "left out: --skip Stand")]


def test_an_incomplete_scan_refuses() -> None:
    plan = _plan(_scan(complete=False))

    assert plan.refusals == ["the build child stopped before the end"]
    assert plan.devices == []
    assert not plan.writable


def test_a_refused_plan_has_no_file() -> None:
    plan = _plan(_scan(complete=False))

