def test_property_lines_of_devices_are_set_aside_never_dropped() -> None:
    previous = _cfg(
        "Property,Cam,MaximumExposureMs,10000.0",
        "Property,Gone,Number of positions,10",
        "Property,Core,Galvo,Scanner",
        "Property,Core,Initialize,0",
        "Property,Core,Initialize,1",
    )

    plan = _plan(_scan(), previous)

    assert [block.lines[0] for block, _ in plan.not_carried] == [
        "Property,Cam,MaximumExposureMs,10000.0",
        "Property,Gone,Number of positions,10",
        "Property,Core,Galvo,Scanner",
    ]
    reasons = [why for _, why in plan.not_carried]
    assert reasons[0] == reasons[1]
    assert "put it in a preset (System/Startup)" in reasons[0]
    assert "Core setting" in reasons[2]
    text = _text(plan)
    for block, _ in plan.not_carried:
        assert NOT_CARRIED + block.lines[0] in text
        assert block.lines[0] not in text
    # What the build writes itself is not read back as a second copy.
    assert text.count("Property,Core,Initialize,0") == 1
    assert text.count("Property,Core,Initialize,1") == 1


