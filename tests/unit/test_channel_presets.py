"""The pure half of ``Channels``: the group, the checks and the ``.cfg`` edit (m2 §8.5).

No core: ``smc.hardware.channels`` imports no Micro-Manager code (ADR-0004).
The ``.cfg`` lines are those of ``profiles/nikon-ti2.cfg`` and of the demo.
"""

from __future__ import annotations

import re

import pytest
from hypothesis import given
from hypothesis import strategies as st

from smc.hardware.channels import (
    check_preset_name,
    check_value,
    choose_group,
    forbidden_settings,
    named_for_channels,
    replace_preset,
    setting_matches,
)
from smc.hardware.errors import HardwareError

DEMO_GROUPS = (
    "Camera",
    "Channel",
    "Channel-Multiband",
    "LightPath",
    "Objective",
    "System",
)

#: The Ti2-E's types, from tests/data/nikon-ti2-devices.json.
TI2_TYPES = {
    "ZDrive": "Stage",
    "XYStage": "XYStage",
    "Nosepiece": "State",
    "CondenserTurret": "State",
    "FilterTurret2": "State",
    "LightPath": "State",
    "PFS": "AutoFocus",
    "PFSOffset": "Stage",
    "DiaLamp": "Shutter",
    "Camera-1": "Camera",
}

BF = [
    ("CondenserTurret", "Label", "7-N2"),
    ("LightPath", "Label", "4-L100"),
    ("DiaLamp", "Intensity", "210"),
]

CFG = (
    "# Generated by Micro-Manager Hardware Configuration Wizard\n"
    "Property,Core,Initialize,1\n"
    "# Group: Channel\n"
    "# Preset: BF\n"
    "ConfigGroup,Channel,BF,CondenserTurret,Label,7-N2\n"
    "ConfigGroup,Channel,BF,DiaLamp,Intensity,210\n"
    "ConfigGroup,Channel,BF,Camera-1,Exposure,10\n"
    "# Preset: BF2\n"
    "ConfigGroup,Channel,BF2,DiaLamp,Intensity,300\n"
    "\n"
    "# Group: LightPath\n"
    "ConfigGroup,LightPath,Eyepiece,LightPath,Label,1-EYE\n"
    "ConfigPixelSize,Res10x,Nosepiece,Label,2-Plan Fluor 10x\n"
)


# --- the group ----------------------------------------------------------------


@pytest.mark.parametrize(
    ("group", "named"),
    [
        ("Channel", True),
        ("Channels", True),
        ("channel", True),
        ("Channel-Multiband", True),
        ("Camera", False),
        ("Objective", False),
        ("System", False),
        ("Camera-Channel", False),
        ("Objective Channel", False),
        ("System Channel", False),
        ("LightPath", False),
    ],
)
def test_a_camera_or_objective_group_is_never_named_for_channels(
    group: str, named: bool
) -> None:
    assert named_for_channels(group) is named


def test_the_profile_group_wins_even_before_it_exists() -> None:
    assert choose_group(DEMO_GROUPS, core_group="Channel", profile_group="Mine") == (
        "Mine",
        [],
    )
    assert choose_group((), core_group="", profile_group="Mine") == ("Mine", [])


def test_the_core_channel_group_wins_over_another_channel_group() -> None:
    assert choose_group(
        DEMO_GROUPS, core_group="Channel-Multiband", profile_group=""
    ) == ("Channel-Multiband", [])
    assert choose_group(DEMO_GROUPS, core_group="Channel", profile_group="") == (
        "Channel",
        [],
    )
    # The Ti2-E: its file has no Core,ChannelGroup line, and one group.
    assert choose_group(("Channel",), core_group="", profile_group="") == (
        "Channel",
        [],
    )


def test_two_channel_groups_without_a_choice_give_none_and_a_warning() -> None:
    group, warnings = choose_group(DEMO_GROUPS, core_group="", profile_group="")
    assert group is None
    assert warnings == [
        "channels: several config groups are named for channels ('Channel', "
        "'Channel-Multiband') and the core's channel group ('') is none of them, "
        "so none is chosen; name one in the profile's [channels] group"
    ]
    assert choose_group(("Camera", "System"), core_group="", profile_group="") == (
        None,
        [],
    )


def test_a_core_channel_group_not_named_for_channels_is_ignored() -> None:
    assert choose_group(
        ("Camera", "Channel", "Objective"), core_group="Objective", profile_group=""
    ) == ("Channel", [])
    # Nor is one that does not exist.
    assert choose_group(("Channel",), core_group="Gone", profile_group="") == (
        "Channel",
        [],
    )


# --- the checks -------------------------------------------------------------


@pytest.mark.parametrize(
    ("name", "problem"),
    [
        ("", "it is empty"),
        ("a,b", "it contains a comma, which separates the fields of a .cfg line"),
        (" a", "it starts or ends with whitespace, which MMCore does not keep"),
        ("a ", "it starts or ends with whitespace, which MMCore does not keep"),
        ("a\n", "it contains a character that is not printable ASCII"),
        ("µ", "it contains a character that is not printable ASCII"),
    ],
)
def test_preset_names_that_would_corrupt_the_cfg_are_refused(
    name: str, problem: str
) -> None:
    message = f"channel preset name {name!r} is refused: {problem}"
    with pytest.raises(ValueError, match=f"^{re.escape(message)}$"):
        check_preset_name(name)


def test_ordinary_preset_names_pass() -> None:
    for name in ("BF", "GFP 488", "smc-contract", "Cy5_long exposure"):
        check_preset_name(name)


def test_a_preset_that_moves_a_stage_autofocus_or_turret_is_refused() -> None:
    settings = [
        ("CondenserTurret", "Label", "7-N2"),
        ("ZDrive", "Position", "10"),
        ("XYStage", "Speed", "1"),
        ("PFS", "FocusMaintenance", "On"),
        ("PFSOffset", "Position", "7800"),
        ("Nosepiece", "Label", "1-Plan Fluor 4x"),
        ("Core", "Focus", "PFSOffset"),
        ("Ghost", "Prop", "1"),
        ("Core", "Shutter", "DiaLamp"),
        ("Core", "AutoShutter", "1"),
        ("DiaLamp", "Intensity", "210"),
    ]
    assert forbidden_settings(
        settings, device_types=TI2_TYPES, objective_turret="Nosepiece"
    ) == [
        "ZDrive,Position: 'ZDrive' is a Stage device (use ZStage)",
        "XYStage,Speed: 'XYStage' is a XYStage device (use XYStage)",
        "PFS,FocusMaintenance: 'PFS' is a AutoFocus device (use Autofocus)",
        "PFSOffset,Position: 'PFSOffset' is a Stage device (use ZStage)",
        "Nosepiece,Label: 'Nosepiece' is the objective turret (use "
        "ObjectiveTurret.select with confirm=True)",
        "Core,Focus changes a core slot",
        "Ghost,Prop: 'Ghost' is not loaded",
    ]
    assert forbidden_settings(BF, device_types=TI2_TYPES, objective_turret=None) == []
    # Without an objective_turret role, the turret is a State device like any other.
    assert (
        forbidden_settings(
            [("Nosepiece", "Label", "1-")],
            device_types=TI2_TYPES,
            objective_turret=None,
        )
        == []
    )


@pytest.mark.parametrize("value", ["", "a,b", "Ω", "a\tb", "\udcff"])
def test_a_value_with_a_comma_or_non_ascii_is_refused(value: str) -> None:
    with pytest.raises(HardwareError) as refused:
        check_value("FilterTurret2", "Label", value)
    message = str(refused.value)
    assert message.startswith(f"FilterTurret2,Label reads {value!r}, which a ")
    assert "nothing was written" in message
    # FM-05: the message itself can be logged and serialised.
    message.encode("utf-8")


def test_a_value_with_spaces_and_dashes_passes() -> None:
    check_value("FilterTurret2", "Label", "2-MXR00700 -96372 - GF")
    check_value("DiaLamp", "Intensity", "210.5")


def test_numbers_match_across_formats() -> None:
    assert setting_matches("10", "10.0000")
    assert setting_matches("10.0000", "10")
    assert setting_matches("1-ANALY", "1-ANALY")
    assert not setting_matches("210", "210.5")
    assert not setting_matches("1-ANALY", "2-ANALY")
    assert not setting_matches("10", "ten")
    for bad in ("nan", "NaN", "inf"):
        assert not setting_matches(bad, bad)
        assert not setting_matches("10", bad)


# --- the .cfg edit --------------------------------------------------------------


def test_replacing_a_preset_keeps_every_other_line_byte_for_byte() -> None:
    edited = replace_preset(CFG, "Channel", "BF", BF)
    assert edited == CFG.replace(
        "ConfigGroup,Channel,BF,CondenserTurret,Label,7-N2\n"
        "ConfigGroup,Channel,BF,DiaLamp,Intensity,210\n"
        "ConfigGroup,Channel,BF,Camera-1,Exposure,10\n",
        "ConfigGroup,Channel,BF,CondenserTurret,Label,7-N2\n"
        "ConfigGroup,Channel,BF,LightPath,Label,4-L100\n"
        "ConfigGroup,Channel,BF,DiaLamp,Intensity,210\n",
    )


def test_replacing_bf_leaves_bf2_untouched() -> None:
    edited = replace_preset(CFG, "Channel", "BF", [("DiaLamp", "Intensity", "1")])
    assert "ConfigGroup,Channel,BF2,DiaLamp,Intensity,300\n" in edited
    assert edited.count("ConfigGroup,Channel,BF,") == 1
    # A preset whose fields carry spaces is still the preset.
    spaced = CFG.replace(
        "ConfigGroup,Channel,BF,Camera-1", "ConfigGroup, Channel , BF ,Camera-1"
    )
    assert "Camera-1" not in replace_preset(spaced, "Channel", "BF", BF)


def test_a_new_preset_goes_after_its_group_and_a_new_group_at_the_end() -> None:
    added = replace_preset(CFG, "Channel", "GFP", [("FilterTurret2", "Label", "2-")])
    assert added == CFG.replace(
        "ConfigGroup,Channel,BF2,DiaLamp,Intensity,300\n",
        "ConfigGroup,Channel,BF2,DiaLamp,Intensity,300\n"
        "ConfigGroup,Channel,GFP,FilterTurret2,Label,2-\n",
    )
    grouped = replace_preset(CFG, "Mine", "a", [("DiaLamp", "Intensity", "5")])
    assert grouped == CFG + "ConfigGroup,Mine,a,DiaLamp,Intensity,5\n"
    # A file without a final line ending gets one before the new line.
    assert replace_preset("Property,Core,Initialize,1", "Mine", "a", BF[:1]) == (
        "Property,Core,Initialize,1\nConfigGroup,Mine,a,CondenserTurret,Label,7-N2\n"
    )


def test_crlf_stays_crlf() -> None:
    windows = CFG.replace("\n", "\r\n")
    edited = replace_preset(windows, "Channel", "BF", BF)
    assert edited == replace_preset(CFG, "Channel", "BF", BF).replace("\n", "\r\n")
    added = replace_preset(windows.rstrip("\r\n"), "Mine", "a", BF[:1])
    assert added.endswith(
        "Res10x,Nosepiece,Label,2-Plan Fluor 10x\r\nConfigGroup,Mine,a,CondenserTurret,"
        "Label,7-N2\r\n"
    )
    assert "\n" not in added.replace("\r\n", "")


_LINE = st.text(
    alphabet=st.characters(min_codepoint=0x20, max_codepoint=0x7E), max_size=30
)


# At least one line: an empty file has no line ending to follow.
@given(st.lists(_LINE, min_size=1, max_size=12), st.booleans())
def test_any_line_that_is_not_the_presets_survives(
    lines: list[str], crlf: bool
) -> None:
    eol = "\r\n" if crlf else "\n"
    text = "".join(line + eol for line in lines)
    edited = replace_preset(text, "Channel", "BF", BF)
    survivors = [
        line
        for line in lines
        if [f.strip() for f in line.split(",")][:3] != ["ConfigGroup", "Channel", "BF"]
    ]
    remaining = edited.split(eol)[:-1]
    new = [f"ConfigGroup,Channel,BF,{d},{p},{v}" for d, p, v in BF]
    for line in new:
        remaining.remove(line)
    assert remaining == survivors
    assert edited.endswith(eol)
